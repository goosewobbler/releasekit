import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { afterEach, describe, expect, it } from 'vitest';
import { findCargoLockfile, setCargoLockVersion, syncCargoLockVersion } from '../../src/cargo.js';

describe('findCargoLockfile', () => {
  const tmpDirs: string[] = [];

  function tmp(): string {
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'rk-cargo-lock-'));
    tmpDirs.push(dir);
    return fs.realpathSync(dir);
  }

  afterEach(() => {
    for (const dir of tmpDirs) fs.rmSync(dir, { recursive: true, force: true });
    tmpDirs.length = 0;
  });

  it('should return the lock in the start dir when present', () => {
    const dir = tmp();
    const lock = path.join(dir, 'Cargo.lock');
    fs.writeFileSync(lock, '');
    expect(findCargoLockfile(dir)).toBe(lock);
  });

  it('should walk up to the nearest ancestor lock for a workspace member', () => {
    const root = tmp();
    const lock = path.join(root, 'Cargo.lock');
    fs.writeFileSync(lock, '');
    const member = path.join(root, 'crates', 'foo');
    fs.mkdirSync(member, { recursive: true });
    expect(findCargoLockfile(member)).toBe(lock);
  });

  it('should return the nearest lock for a standalone (non-workspace) crate when both a member and an ancestor have one', () => {
    // No [workspace] manifest anywhere → the standalone fallback (nearest lock wins). With a
    // workspace root present, the root lock would win instead — see the workspace-root test below.
    const root = tmp();
    fs.writeFileSync(path.join(root, 'Cargo.lock'), '');
    const member = path.join(root, 'crates', 'foo');
    fs.mkdirSync(member, { recursive: true });
    const memberLock = path.join(member, 'Cargo.lock');
    fs.writeFileSync(memberLock, '');
    expect(findCargoLockfile(member)).toBe(memberLock);
  });

  it('should return undefined when no lock exists above the start dir', () => {
    const dir = tmp();
    const member = path.join(dir, 'crates', 'foo');
    fs.mkdirSync(member, { recursive: true });
    expect(findCargoLockfile(member)).toBeUndefined();
  });

  it('should target the workspace-root lock, not a member’s own stray lock', () => {
    const root = tmp();
    fs.writeFileSync(path.join(root, 'Cargo.toml'), '[workspace]\nmembers = ["crates/foo"]\n');
    const rootLock = path.join(root, 'Cargo.lock');
    fs.writeFileSync(rootLock, '');
    const member = path.join(root, 'crates', 'foo');
    fs.mkdirSync(member, { recursive: true });
    fs.writeFileSync(path.join(member, 'Cargo.toml'), '[package]\nname = "foo"\nversion = "1.0.0"\n');
    // A stray lock in the member dir is ignored by cargo — the workspace-root lock is the one that moves.
    fs.writeFileSync(path.join(member, 'Cargo.lock'), '');
    expect(findCargoLockfile(member)).toBe(rootLock);
  });

  it('should return undefined when the workspace root has no committed lock', () => {
    const root = tmp();
    fs.writeFileSync(path.join(root, 'Cargo.toml'), '[workspace]\nmembers = ["crates/foo"]\n');
    const member = path.join(root, 'crates', 'foo');
    fs.mkdirSync(member, { recursive: true });
    fs.writeFileSync(path.join(member, 'Cargo.toml'), '[package]\nname = "foo"\nversion = "1.0.0"\n');
    // No lock at the workspace root → nothing to sync (don't fall back to a stray member lock).
    fs.writeFileSync(path.join(member, 'Cargo.lock'), '');
    expect(findCargoLockfile(member)).toBeUndefined();
  });
});

const REGISTRY = 'registry+https://github.com/rust-lang/crates.io-index';
const GIT = 'git+https://github.com/example/dupe#9a1327a6d3f8bc80a0f02fe01325c7828d587668';

/** Join lock lines the way cargo writes them: LF endings and a trailing newline. */
const lock = (...lines: string[]): string => `${lines.join('\n')}\n`;

describe('setCargoLockVersion', () => {
  it.each([3, 4])('should bump only the crate’s own entry in a v%i lock', (format) => {
    const before = lock(
      '# This file is automatically @generated by Cargo.',
      '# It is not intended for manual editing.',
      `version = ${format}`,
      '',
      '[[package]]',
      'name = "app"',
      'version = "0.1.0"',
      'dependencies = [',
      ' "core",',
      ']',
      '',
      '[[package]]',
      'name = "core"',
      'version = "1.4.0"',
    );

    expect(setCargoLockVersion(before, 'core', '1.5.0')).toBe(before.replace('version = "1.4.0"', 'version = "1.5.0"'));
  });

  it('should rewrite versioned references when the lock holds two versions of the name', () => {
    // Byte-for-byte what `cargo update --workspace` writes after bumping the path crate `dupe`.
    const before = lock(
      'version = 4',
      '',
      '[[package]]',
      'name = "app"',
      'version = "0.1.0"',
      'dependencies = [',
      ' "dupe 0.9.0",',
      ' "dupe 1.0.0",',
      ']',
      '',
      '[[package]]',
      'name = "dupe"',
      'version = "0.9.0"',
      `source = "${GIT}"`,
      '',
      '[[package]]',
      'name = "dupe"',
      'version = "1.0.0"',
    );
    const after = lock(
      'version = 4',
      '',
      '[[package]]',
      'name = "app"',
      'version = "0.1.0"',
      'dependencies = [',
      ' "dupe 0.9.0",',
      ' "dupe 1.1.0",',
      ']',
      '',
      '[[package]]',
      'name = "dupe"',
      'version = "0.9.0"',
      `source = "${GIT}"`,
      '',
      '[[package]]',
      'name = "dupe"',
      'version = "1.1.0"',
    );

    expect(setCargoLockVersion(before, 'dupe', '1.1.0')).toBe(after);
  });

  it('should rewrite path references in a v1 lock without touching registry references or checksums', () => {
    // v1 locks always spell out the version, and add the source for registry packages.
    const before = lock(
      '[[package]]',
      'name = "app"',
      'version = "0.1.0"',
      'dependencies = [',
      ' "core 1.4.0",',
      ` "serde 1.0.200 (${REGISTRY})",`,
      ']',
      '',
      '[[package]]',
      'name = "core"',
      'version = "1.4.0"',
      '',
      '[[package]]',
      'name = "serde"',
      'version = "1.0.200"',
      `source = "${REGISTRY}"`,
      '',
      '[metadata]',
      `"checksum serde 1.0.200 (${REGISTRY})" = "ddc6f9cc94d67c0e21aaf7eda3a010fd3af78ebf6e096aa6e2e13c79749cce4f"`,
    );

    expect(setCargoLockVersion(before, 'core', '2.0.0')).toBe(
      before.replace('"core 1.4.0"', '"core 2.0.0"').replace('version = "1.4.0"', 'version = "2.0.0"'),
    );
  });

  it('should return undefined when the crate is only in the lock as a registry package', () => {
    const before = lock(
      'version = 3',
      '',
      '[[package]]',
      'name = "serde"',
      'version = "1.0.200"',
      `source = "${REGISTRY}"`,
    );

    expect(setCargoLockVersion(before, 'serde', '1.0.201')).toBeUndefined();
  });

  it('should return the content unchanged when the entry is already at the version', () => {
    const before = lock('version = 3', '', '[[package]]', 'name = "core"', 'version = "1.5.0"');

    expect(setCargoLockVersion(before, 'core', '1.5.0')).toBe(before);
  });

  it('should keep CRLF line endings', () => {
    const before = 'version = 3\r\n\r\n[[package]]\r\nname = "core"\r\nversion = "1.4.0"\r\n';

    expect(setCargoLockVersion(before, 'core', '1.5.0')).toBe(before.replace('1.4.0', '1.5.0'));
  });

  it.each([
    ['the new version', '2.0.0'],
    ['the old version', '1.4.0'],
  ])('should throw when another source holds the name at %s', (_label, otherVersion) => {
    const before = lock(
      'version = 4',
      '',
      '[[package]]',
      'name = "core"',
      'version = "1.4.0"',
      '',
      '[[package]]',
      'name = "core"',
      `version = "${otherVersion}"`,
      `source = "${REGISTRY}"`,
    );

    expect(() => setCargoLockVersion(before, 'core', '2.0.0')).toThrow(/from another source/);
  });
});

describe('syncCargoLockVersion', () => {
  const tmpDirs: string[] = [];

  function workspaceWithLock(): { root: string; member: string; lockPath: string } {
    const root = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), 'rk-cargo-lock-sync-')));
    tmpDirs.push(root);
    fs.writeFileSync(path.join(root, 'Cargo.toml'), '[workspace]\nmembers = ["crates/core"]\n');
    const member = path.join(root, 'crates', 'core');
    fs.mkdirSync(member, { recursive: true });
    const lockPath = path.join(root, 'Cargo.lock');
    fs.writeFileSync(lockPath, lock('version = 4', '', '[[package]]', 'name = "core"', 'version = "1.4.0"'));
    return { root, member, lockPath };
  }

  afterEach(() => {
    for (const dir of tmpDirs) fs.rmSync(dir, { recursive: true, force: true });
    tmpDirs.length = 0;
  });

  it('should write the bumped entry to the workspace-root lock', () => {
    const { member, lockPath } = workspaceWithLock();

    expect(syncCargoLockVersion(member, 'core', '1.5.0')).toEqual({ lockPath, changed: true });
    expect(fs.readFileSync(lockPath, 'utf8')).toContain('version = "1.5.0"');
  });

  it('should report the change without writing under dry-run', () => {
    const { member, lockPath } = workspaceWithLock();

    expect(syncCargoLockVersion(member, 'core', '1.5.0', true)).toEqual({ lockPath, changed: true });
    expect(fs.readFileSync(lockPath, 'utf8')).toContain('version = "1.4.0"');
  });

  it('should return undefined when no committed lock lists the crate', () => {
    const { member } = workspaceWithLock();

    expect(syncCargoLockVersion(member, 'other', '1.5.0')).toBeUndefined();
  });
});
