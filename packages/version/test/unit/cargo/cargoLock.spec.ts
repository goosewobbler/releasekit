/**
 * Cargo.lock sync across every path that bumps a Cargo.toml (#496, #650). Each test runs a real
 * strategy through `VersionEngine.run` over a real git work tree on disk — only tag lookups, commit
 * parsing and the version calculation are mocked — and checks the locks the standing-PR flow stages
 * with `git add -A`: the crates' own workspace lock and a fixture app's lock that uses them by path.
 */
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import type { Package, Tool } from '@manypkg/get-packages';
import { EXIT_CODES, exitCodeForError } from '@releasekit/core';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import * as commitParser from '../../../src/changelog/commitParser.js';
import * as calculator from '../../../src/core/versionCalculator.js';
import { type PackagesWithRoot, VersionEngine } from '../../../src/core/versionEngine.js';
import type { StrategyType } from '../../../src/core/versionStrategies.js';
import * as gitTags from '../../../src/git/tagsAndBranches.js';
import * as tagVerification from '../../../src/git/tagVerification.js';
import type { Config } from '../../../src/types.js';
import { enableJsonOutput, flushPendingWrites } from '../../../src/utils/jsonOutput.js';

vi.mock('../../../src/git/tagsAndBranches.js');
vi.mock('../../../src/git/tagVerification.js');
vi.mock('../../../src/core/versionCalculator.js');
vi.mock('../../../src/changelog/commitParser.js');
vi.mock('../../../src/utils/logging.js');

const REGISTRY = 'registry+https://github.com/rust-lang/crates.io-index';
const CHECKSUM = 'checksum = "ddc6f9cc94d67c0e21aaf7eda3a010fd3af78ebf6e096aa6e2e13c79749cce4f"';

type Versions = { alpha: string; beta: string };

/** The workspace lock as cargo writes it: alpha depends on beta (path) and serde (registry). */
function workspaceLock(versions: Versions): string {
  return [
    '# This file is automatically @generated by Cargo.',
    '# It is not intended for manual editing.',
    'version = 3',
    '',
    '[[package]]',
    'name = "alpha"',
    `version = "${versions.alpha}"`,
    'dependencies = [',
    ' "beta",',
    ' "serde",',
    ']',
    '',
    '[[package]]',
    'name = "beta"',
    `version = "${versions.beta}"`,
    '',
    '[[package]]',
    'name = "serde"',
    'version = "1.0.200"',
    `source = "${REGISTRY}"`,
    CHECKSUM,
    '',
  ].join('\n');
}

/**
 * The fixture app's lock: it uses alpha by path and also the published alpha 0.9.0, so cargo spells
 * out versions in references to alpha, and the registry entry must never move.
 */
function appLock(versions: Versions): string {
  return [
    'version = 4',
    '',
    '[[package]]',
    'name = "alpha"',
    'version = "0.9.0"',
    `source = "${REGISTRY}"`,
    CHECKSUM,
    '',
    '[[package]]',
    'name = "alpha"',
    `version = "${versions.alpha}"`,
    'dependencies = [',
    ' "beta",',
    ' "serde",',
    ']',
    '',
    '[[package]]',
    'name = "beta"',
    `version = "${versions.beta}"`,
    '',
    '[[package]]',
    'name = "fixture-app"',
    'version = "0.1.0"',
    'dependencies = [',
    ' "alpha 0.9.0",',
    ` "alpha ${versions.alpha}",`,
    ']',
    '',
    '[[package]]',
    'name = "serde"',
    'version = "1.0.200"',
    `source = "${REGISTRY}"`,
    CHECKSUM,
    '',
  ].join('\n');
}

function writeCrate(dir: string, name: string, version: string, extra = ''): void {
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(
    path.join(dir, 'Cargo.toml'),
    `[package]\nname = "${name}"\nversion = "${version}"\nedition = "2021"\n${extra}`,
  );
}

function crate(root: string, name: string): Package {
  return {
    dir: path.join(root, 'crates', name),
    relativeDir: `crates/${name}`,
    packageJson: { name, version: '1.0.0' },
  } as unknown as Package;
}

function workspace(root: string, packages: Package[]): PackagesWithRoot {
  return { root, rootDir: root, tool: 'cargo' as unknown as Tool, packages } as unknown as PackagesWithRoot;
}

const baseConfig = (overrides: Partial<Config> = {}): Config =>
  ({
    sync: false,
    preset: 'conventional',
    packages: [],
    tagTemplate: '${prefix}${version}',
    versionPrefix: 'v',
    ...overrides,
  }) as Config;

/** Make `calculateVersion` bump exactly the named packages. */
function bump(next: Record<string, string>): void {
  vi.mocked(calculator.calculateVersion).mockImplementation(async (_config, options) => next[options.name ?? ''] ?? '');
}

/** Run one strategy the way the version CLI and the release flows do: through `VersionEngine.run`. */
async function runVersion(strategy: StrategyType, config: Partial<Config>, packages: PackagesWithRoot): Promise<void> {
  const engine = new VersionEngine(baseConfig(config));
  engine.setStrategy(strategy);
  await engine.run(packages);
}

const git = (cwd: string, ...args: string[]): string => execFileSync('git', args, { cwd, encoding: 'utf8' });

describe('Cargo.lock sync on Cargo.toml bumps', () => {
  let root: string;
  let ownLock: string;
  let fixtureLock: string;

  const read = (file: string): string => fs.readFileSync(file, 'utf8');
  const both = (): Package[] => [crate(root, 'alpha'), crate(root, 'beta')];

  beforeEach(() => {
    vi.resetAllMocks();
    vi.mocked(gitTags.getLatestTag).mockResolvedValue('');
    vi.mocked(gitTags.getLatestTagForPackage).mockResolvedValue('');
    vi.mocked(tagVerification.verifyTag, { partial: true }).mockResolvedValue({ exists: true, reachable: true });
    vi.mocked(commitParser.extractChangelogEntriesFromCommits).mockResolvedValue([]);
    vi.mocked(commitParser.extractRepoLevelChangelogEntries).mockResolvedValue([]);

    root = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), 'rk-cargo-lock-paths-')));
    fs.mkdirSync(path.join(root, 'crates'));
    fs.writeFileSync(path.join(root, 'crates', 'Cargo.toml'), '[workspace]\nmembers = ["alpha", "beta"]\n');
    writeCrate(
      path.join(root, 'crates', 'alpha'),
      'alpha',
      '1.0.0',
      '\n[dependencies]\nbeta = { path = "../beta" }\nserde = "1"\n',
    );
    writeCrate(path.join(root, 'crates', 'beta'), 'beta', '1.0.0');
    ownLock = path.join(root, 'crates', 'Cargo.lock');
    fs.writeFileSync(ownLock, workspaceLock({ alpha: '1.0.0', beta: '1.0.0' }));

    writeCrate(
      path.join(root, 'fixtures', 'app'),
      'fixture-app',
      '0.1.0',
      'publish = false\n\n[workspace]\n\n[dependencies]\nalpha = { path = "../../crates/alpha" }\nalpha-old = { package = "alpha", version = "0.9" }\n',
    );
    fixtureLock = path.join(root, 'fixtures', 'app', 'Cargo.lock');
    fs.writeFileSync(fixtureLock, appLock({ alpha: '1.0.0', beta: '1.0.0' }));

    git(root, 'init', '-q');
    git(root, 'add', '-A');
  });

  afterEach(() => {
    fs.rmSync(root, { recursive: true, force: true });
  });

  it.each<[string, StrategyType, Partial<Config>, 'alpha' | 'both', Versions]>([
    [
      'a version group',
      'group',
      { groups: { rust: { packages: ['alpha', 'beta'], sync: 'fixed' } } },
      'both',
      { alpha: '1.1.0', beta: '1.1.0' },
    ],
    [
      'the ungrouped path in group mode',
      'group',
      { groups: { other: { packages: ['beta'], sync: 'fixed' } } },
      'both',
      { alpha: '1.1.0', beta: '1.0.0' },
    ],
    ['the per-package processor', 'async', {}, 'both', { alpha: '1.1.0', beta: '1.0.0' }],
    ['updateCargoFiles in a sync release', 'sync', { sync: true }, 'both', { alpha: '1.1.0', beta: '1.1.0' }],
    ['updateCargoFiles in a single-package release', 'single', {}, 'alpha', { alpha: '1.1.0', beta: '1.0.0' }],
  ])(
    'should sync every lock that records a crate bumped through %s',
    async (_label, strategy, config, scope, expected) => {
      bump({ alpha: '1.1.0' });
      const packages = scope === 'both' ? both() : [crate(root, 'alpha')];

      await runVersion(strategy, config, workspace(root, packages));

      expect(read(ownLock)).toBe(workspaceLock(expected));
      expect(read(fixtureLock)).toBe(appLock(expected));
      expect(git(root, 'diff', '--name-only', '--', '*.lock')).toBe('crates/Cargo.lock\nfixtures/app/Cargo.lock\n');
    },
  );

  it('should sync the lock for a Cargo.toml found through cargo.paths (Tauri layout)', async () => {
    // A JS package whose crate lives in src-tauri/ with its own committed lock.
    const appDir = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), 'rk-cargo-lock-tauri-')));
    const crateLock = path.join(appDir, 'src-tauri', 'Cargo.lock');
    fs.writeFileSync(path.join(appDir, 'package.json'), '{ "name": "desktop", "version": "0.4.0" }\n');
    writeCrate(path.join(appDir, 'src-tauri'), 'desktop', '0.4.0');
    fs.writeFileSync(crateLock, 'version = 4\n\n[[package]]\nname = "desktop"\nversion = "0.4.0"\n');
    const app = { dir: appDir, relativeDir: '.', packageJson: { name: 'desktop', version: '0.4.0' } } as unknown;
    bump({ desktop: '0.5.0' });

    try {
      await runVersion(
        'async',
        { cargo: { enabled: true, paths: ['src-tauri'] } },
        workspace(appDir, [app as Package]),
      );
      expect(read(crateLock)).toBe('version = 4\n\n[[package]]\nname = "desktop"\nversion = "0.5.0"\n');
    } finally {
      fs.rmSync(appDir, { recursive: true, force: true });
    }
  });

  const tauriLock = (version: string): string => `version = 4\n\n[[package]]\nname = "app"\nversion = "${version}"\n`;
  const tauriLockOf = (name: string): string => path.join(root, 'apps', name, 'src-tauri', 'Cargo.lock');

  /** A JS package `apps/<name>` whose src-tauri crate has the `tauri init` name, `app`. */
  function tauriApp(name: string, version: string, withLock = true): Package {
    const dir = path.join(root, 'apps', name);
    writeCrate(path.join(dir, 'src-tauri'), 'app', version);
    if (withLock) {
      fs.writeFileSync(tauriLockOf(name), tauriLock(version));
    }
    fs.writeFileSync(path.join(dir, 'package.json'), `{ "name": "${name}", "version": "${version}" }\n`);
    return { dir, relativeDir: `apps/${name}`, packageJson: { name, version } } as unknown as Package;
  }

  it.each([
    ['both apps', { one: '0.2.0', two: '0.1.1' }],
    ['one app', { one: '0.2.0' }],
  ])(
    'should sync each Tauri app’s lock to its own crate when the crates share a name (%s bumped)',
    async (_label, next: Record<string, string>) => {
      const apps = [tauriApp('one', '0.1.0'), tauriApp('two', '0.1.0')];
      git(root, 'add', '-A');
      bump(next);

      await runVersion('async', { cargo: { enabled: true, paths: ['src-tauri'] } }, workspace(root, apps));

      for (const name of ['one', 'two']) {
        expect(read(tauriLockOf(name))).toBe(tauriLock(next[name] ?? '0.1.0'));
      }
    },
  );

  it('should sync excluded apps’ own locks, not the ancestor workspace’s, when the crates share a name', async () => {
    fs.writeFileSync(
      path.join(root, 'Cargo.toml'),
      '[workspace]\nmembers = ["shared"]\nexclude = ["apps/one/src-tauri", "apps/two/src-tauri"]\n',
    );
    const rootLock = 'version = 4\n\n[[package]]\nname = "shared"\nversion = "1.0.0"\n';
    fs.writeFileSync(path.join(root, 'Cargo.lock'), rootLock);
    const apps = [tauriApp('one', '0.1.0'), tauriApp('two', '0.3.0')];
    git(root, 'add', '-A');
    bump({ one: '0.2.0', two: '0.4.0' });

    await runVersion('async', { cargo: { enabled: true, paths: ['src-tauri'] } }, workspace(root, apps));

    expect(read(tauriLockOf('one'))).toBe(tauriLock('0.2.0'));
    expect(read(tauriLockOf('two'))).toBe(tauriLock('0.4.0'));
    expect(read(path.join(root, 'Cargo.lock'))).toBe(rootLock);
  });

  it('should leave an ancestor workspace’s member alone when an excluded crate of the same name is bumped', async () => {
    fs.writeFileSync(
      path.join(root, 'Cargo.toml'),
      '[workspace]\nmembers = ["apps/one/src-tauri"]\nexclude = ["apps/two/src-tauri"]\n',
    );
    fs.writeFileSync(path.join(root, 'Cargo.lock'), tauriLock('0.1.0'));
    const apps = [tauriApp('one', '0.1.0', false), tauriApp('two', '0.3.0')];
    git(root, 'add', '-A');
    bump({ two: '0.4.0' });

    await runVersion('async', { cargo: { enabled: true, paths: ['src-tauri'] } }, workspace(root, apps));

    expect(read(tauriLockOf('two'))).toBe(tauriLock('0.4.0'));
    expect(read(path.join(root, 'Cargo.lock'))).toBe(tauriLock('0.1.0'));
  });

  it('should sync the lock of a crate that an ancestor Cargo workspace excludes', async () => {
    fs.writeFileSync(path.join(root, 'Cargo.toml'), '[workspace]\nexclude = ["apps/desk/src-tauri"]\n');
    const appDir = path.join(root, 'apps', 'desk');
    const appLock = path.join(appDir, 'src-tauri', 'Cargo.lock');
    writeCrate(path.join(appDir, 'src-tauri'), 'desk', '0.1.0');
    fs.writeFileSync(appLock, 'version = 4\n\n[[package]]\nname = "desk"\nversion = "0.1.0"\n');
    fs.writeFileSync(path.join(appDir, 'package.json'), '{ "name": "desk", "version": "0.1.0" }\n');
    git(root, 'add', '-A');
    bump({ desk: '0.2.0' });
    const app = { dir: appDir, relativeDir: 'apps/desk', packageJson: { name: 'desk', version: '0.1.0' } };

    await runVersion(
      'async',
      { cargo: { enabled: true, paths: ['src-tauri'] } },
      workspace(root, [app as unknown as Package]),
    );

    expect(read(appLock)).toBe('version = 4\n\n[[package]]\nname = "desk"\nversion = "0.2.0"\n');
  });

  it('should sync the locks without a Rust toolchain or a crates.io index', async () => {
    // A fresh CI runner: git on PATH but no cargo, and an empty CARGO_HOME. Nothing may shell out to cargo.
    const bin = fs.mkdtempSync(path.join(os.tmpdir(), 'rk-no-cargo-'));
    const gitDir = (process.env.PATH ?? '').split(path.delimiter).find((dir) => fs.existsSync(path.join(dir, 'git')));
    fs.symlinkSync(path.join(gitDir as string, 'git'), path.join(bin, 'git'));
    vi.stubEnv('PATH', bin);
    vi.stubEnv('CARGO_HOME', bin);
    bump({ alpha: '1.1.0' });

    try {
      await runVersion('group', { groups: { rust: { packages: ['alpha'], sync: 'fixed' } } }, workspace(root, both()));
    } finally {
      vi.unstubAllEnvs();
      fs.rmSync(bin, { recursive: true, force: true });
    }

    expect(read(ownLock)).toBe(workspaceLock({ alpha: '1.1.0', beta: '1.0.0' }));
    expect(read(fixtureLock)).toBe(appLock({ alpha: '1.1.0', beta: '1.0.0' }));
  });

  it('should leave the locks on disk under dry-run and hand the edits to the release flush', async () => {
    // `release` runs the version step as a dry run with JSON output, then flushes the pending writes.
    enableJsonOutput(true);
    bump({ alpha: '1.1.0' });

    await runVersion('async', { dryRun: true }, workspace(root, both()));

    expect(read(ownLock)).toBe(workspaceLock({ alpha: '1.0.0', beta: '1.0.0' }));
    expect(read(fixtureLock)).toBe(appLock({ alpha: '1.0.0', beta: '1.0.0' }));
    flushPendingWrites();
    expect(read(ownLock)).toBe(workspaceLock({ alpha: '1.1.0', beta: '1.0.0' }));
    expect(read(fixtureLock)).toBe(appLock({ alpha: '1.1.0', beta: '1.0.0' }));
  });

  it('should fail the run, writing no lock, when a committed lock cannot be synced', async () => {
    // A registry copy of beta at the target version: cargo would have to add a source to beta's
    // references, so the sync refuses to guess.
    const ambiguous = `${appLock({ alpha: '1.0.0', beta: '1.0.0' }).replace(' "beta",', ' "beta 1.0.0",')}\n[[package]]\nname = "beta"\nversion = "2.0.0"\nsource = "${REGISTRY}"\n`;
    fs.writeFileSync(fixtureLock, ambiguous);
    bump({ beta: '2.0.0' });

    const run = runVersion('async', {}, workspace(root, both()));

    await expect(run).rejects.toMatchObject({ code: 'CARGO_LOCK_SYNC_ERROR' });
    expect(exitCodeForError(await run.catch((error: unknown) => error))).toBe(EXIT_CODES.VERSION_ERROR);
    expect(read(ownLock)).toBe(workspaceLock({ alpha: '1.0.0', beta: '1.0.0' }));
    expect(read(fixtureLock)).toBe(ambiguous);
  });

  it('should fail a dry run on a lock that cannot be synced, before anything is written', async () => {
    fs.writeFileSync(
      fixtureLock,
      `${read(fixtureLock)}\n[[package]]\nname = "beta"\nversion = "2.0.0"\nsource = "${REGISTRY}"\n`,
    );
    bump({ beta: '2.0.0' });

    await expect(runVersion('async', { dryRun: true }, workspace(root, both()))).rejects.toMatchObject({
      code: 'CARGO_LOCK_SYNC_ERROR',
    });
  });

  it('should sync a crate’s own lock even when untracked, but leave other untracked locks alone', async () => {
    git(root, 'rm', '-q', '--cached', 'crates/Cargo.lock', 'fixtures/app/Cargo.lock');
    bump({ alpha: '1.1.0' });

    await runVersion('async', {}, workspace(root, both()));

    expect(read(ownLock)).toBe(workspaceLock({ alpha: '1.1.0', beta: '1.0.0' }));
    expect(read(fixtureLock)).toBe(appLock({ alpha: '1.0.0', beta: '1.0.0' }));
  });

  it('should not sync a crate’s own lock that git ignores', async () => {
    // A library that ignores its lock, left on disk by an earlier `cargo test`: it can't be staged.
    git(root, 'rm', '-q', '--cached', 'crates/Cargo.lock');
    fs.writeFileSync(path.join(root, '.gitignore'), 'Cargo.lock\n');
    bump({ alpha: '1.1.0' });

    await runVersion('async', {}, workspace(root, both()));

    expect(read(ownLock)).toBe(workspaceLock({ alpha: '1.0.0', beta: '1.0.0' }));
    expect(read(fixtureLock)).toBe(appLock({ alpha: '1.1.0', beta: '1.0.0' }));
  });

  it('should not create a lock when none is committed', async () => {
    fs.rmSync(ownLock);
    fs.rmSync(fixtureLock);
    bump({ alpha: '1.1.0' });

    await runVersion('async', {}, workspace(root, both()));

    expect(fs.existsSync(ownLock)).toBe(false);
    expect(fs.existsSync(fixtureLock)).toBe(false);
    expect(read(path.join(root, 'crates', 'alpha', 'Cargo.toml'))).toContain('version = "1.1.0"');
  });
});
