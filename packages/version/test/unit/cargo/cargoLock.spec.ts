/**
 * Cargo.lock sync across every path that bumps a Cargo.toml (#496, #650). Each test drives a real
 * strategy over a real Cargo workspace on disk — only git, tag lookups and the version calculation are
 * mocked — and checks the committed lock that the standing-PR flow stages with `git add -A`.
 */
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import type { Package, Tool } from '@manypkg/get-packages';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import * as commitParser from '../../../src/changelog/commitParser.js';
import { createGroupStrategy } from '../../../src/core/groupStrategy.js';
import * as calculator from '../../../src/core/versionCalculator.js';
import type { PackagesWithRoot } from '../../../src/core/versionEngine.js';
import { createAsyncStrategy, createSingleStrategy, createSyncStrategy } from '../../../src/core/versionStrategies.js';
import * as gitTags from '../../../src/git/tagsAndBranches.js';
import * as tagVerification from '../../../src/git/tagVerification.js';
import type { Config } from '../../../src/types.js';
import * as logging from '../../../src/utils/logging.js';

vi.mock('../../../src/git/tagsAndBranches.js');
vi.mock('../../../src/git/tagVerification.js');
vi.mock('../../../src/core/versionCalculator.js');
vi.mock('../../../src/changelog/commitParser.js');
vi.mock('../../../src/utils/logging.js');

const REGISTRY = 'registry+https://github.com/rust-lang/crates.io-index';

/** A lock as cargo writes it for the fixture workspace: alpha depends on beta (path) and serde (registry). */
function renderLock(versions: { alpha: string; beta: string }): string {
  return [
    '# This file is automatically @generated by Cargo.',
    '# It is not intended for manual editing.',
    'version = 3',
    '',
    '[[package]]',
    'name = "alpha"',
    `version = "${versions.alpha}"`,
    'dependencies = [',
    ' "beta",',
    ' "serde",',
    ']',
    '',
    '[[package]]',
    'name = "beta"',
    `version = "${versions.beta}"`,
    '',
    '[[package]]',
    'name = "serde"',
    'version = "1.0.200"',
    `source = "${REGISTRY}"`,
    'checksum = "ddc6f9cc94d67c0e21aaf7eda3a010fd3af78ebf6e096aa6e2e13c79749cce4f"',
    '',
  ].join('\n');
}

function writeCrate(dir: string, name: string, version: string, extra = ''): void {
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(
    path.join(dir, 'Cargo.toml'),
    `[package]\nname = "${name}"\nversion = "${version}"\nedition = "2021"\n${extra}`,
  );
}

function crate(root: string, name: string): Package {
  return {
    dir: path.join(root, 'crates', name),
    relativeDir: `crates/${name}`,
    packageJson: { name, version: '1.0.0' },
  } as unknown as Package;
}

function workspace(root: string, packages: Package[]): PackagesWithRoot {
  return { root, rootDir: root, tool: 'cargo' as unknown as Tool, packages } as unknown as PackagesWithRoot;
}

const baseConfig = (overrides: Partial<Config> = {}): Config =>
  ({
    sync: false,
    preset: 'conventional',
    packages: [],
    tagTemplate: '${prefix}${version}',
    versionPrefix: 'v',
    ...overrides,
  }) as Config;

/** Make `calculateVersion` bump exactly the named packages. */
function bump(next: Record<string, string>): void {
  vi.mocked(calculator.calculateVersion).mockImplementation(async (_config, options) => next[options.name ?? ''] ?? '');
}

describe('Cargo.lock sync on Cargo.toml bumps', () => {
  let root: string;
  let lockPath: string;

  const readLock = (): string => fs.readFileSync(lockPath, 'utf8');
  const lockWarnings = (): string[] =>
    vi
      .mocked(logging.log)
      .mock.calls.filter(([message, level]) => level === 'warning' && String(message).includes('Cargo.lock'))
      .map(([message]) => String(message));

  beforeEach(() => {
    vi.resetAllMocks();
    vi.mocked(gitTags.getLatestTag).mockResolvedValue('');
    vi.mocked(gitTags.getLatestTagForPackage).mockResolvedValue('');
    vi.mocked(tagVerification.verifyTag, { partial: true }).mockResolvedValue({ exists: true, reachable: true });
    vi.mocked(commitParser.extractChangelogEntriesFromCommits).mockResolvedValue([]);
    vi.mocked(commitParser.extractRepoLevelChangelogEntries).mockResolvedValue([]);

    root = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), 'rk-cargo-lock-paths-')));
    fs.writeFileSync(path.join(root, 'Cargo.toml'), '[workspace]\nmembers = ["crates/alpha", "crates/beta"]\n');
    writeCrate(
      path.join(root, 'crates', 'alpha'),
      'alpha',
      '1.0.0',
      '\n[dependencies]\nbeta = { path = "../beta" }\nserde = "1"\n',
    );
    writeCrate(path.join(root, 'crates', 'beta'), 'beta', '1.0.0');
    lockPath = path.join(root, 'Cargo.lock');
    fs.writeFileSync(lockPath, renderLock({ alpha: '1.0.0', beta: '1.0.0' }));
  });

  afterEach(() => {
    fs.rmSync(root, { recursive: true, force: true });
  });

  it('should sync the lock for crates bumped through a version group', async () => {
    bump({ alpha: '1.1.0' });
    const strategy = createGroupStrategy(
      baseConfig({ groups: { rust: { packages: ['alpha', 'beta'], sync: 'fixed' } } }),
    );

    await strategy(workspace(root, [crate(root, 'alpha'), crate(root, 'beta')]));

    expect(readLock()).toBe(renderLock({ alpha: '1.1.0', beta: '1.1.0' }));
    expect(lockWarnings()).toEqual([]);
  });

  it('should sync the lock for an ungrouped crate when version groups are configured', async () => {
    bump({ beta: '1.0.1' });
    const strategy = createGroupStrategy(baseConfig({ groups: { app: { packages: ['alpha'], sync: 'fixed' } } }));

    await strategy(workspace(root, [crate(root, 'alpha'), crate(root, 'beta')]));

    expect(readLock()).toBe(renderLock({ alpha: '1.0.0', beta: '1.0.1' }));
  });

  it('should sync the lock for a crate bumped by the per-package (async) strategy', async () => {
    bump({ beta: '2.0.0' });

    await createAsyncStrategy(baseConfig())(workspace(root, [crate(root, 'alpha'), crate(root, 'beta')]));

    expect(readLock()).toBe(renderLock({ alpha: '1.0.0', beta: '2.0.0' }));
  });

  it('should sync the lock for a Cargo.toml found through cargo.paths (Tauri layout)', async () => {
    // A JS package whose crate lives in src-tauri/ with its own committed lock, outside any workspace.
    const appDir = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), 'rk-cargo-lock-tauri-')));
    const crateLock = path.join(appDir, 'src-tauri', 'Cargo.lock');
    fs.writeFileSync(path.join(appDir, 'package.json'), '{ "name": "desktop", "version": "0.4.0" }\n');
    writeCrate(path.join(appDir, 'src-tauri'), 'desktop', '0.4.0');
    fs.writeFileSync(crateLock, 'version = 4\n\n[[package]]\nname = "desktop"\nversion = "0.4.0"\n');
    const app = { dir: appDir, relativeDir: '.', packageJson: { name: 'desktop', version: '0.4.0' } } as unknown;
    bump({ desktop: '0.5.0' });

    try {
      await createAsyncStrategy(baseConfig({ cargo: { enabled: true, paths: ['src-tauri'] } }))(
        workspace(appDir, [app as Package]),
      );
      expect(fs.readFileSync(crateLock, 'utf8')).toBe(
        'version = 4\n\n[[package]]\nname = "desktop"\nversion = "0.5.0"\n',
      );
    } finally {
      fs.rmSync(appDir, { recursive: true, force: true });
    }
  });

  it('should sync the lock for a single-package release', async () => {
    bump({ beta: '1.2.0' });

    await createSingleStrategy(baseConfig())(workspace(root, [crate(root, 'beta')]));

    expect(readLock()).toBe(renderLock({ alpha: '1.0.0', beta: '1.2.0' }));
  });

  it('should sync the lock for every crate in a sync release', async () => {
    bump({ alpha: '1.3.0' });

    await createSyncStrategy(baseConfig({ sync: true }))(workspace(root, [crate(root, 'alpha'), crate(root, 'beta')]));

    expect(readLock()).toBe(renderLock({ alpha: '1.3.0', beta: '1.3.0' }));
  });

  it('should sync the lock without a Rust toolchain or a crates.io index', async () => {
    // A fresh CI runner: no cargo on PATH and an empty CARGO_HOME. Nothing may shell out to cargo.
    const emptyDir = fs.mkdtempSync(path.join(os.tmpdir(), 'rk-no-cargo-'));
    vi.stubEnv('PATH', emptyDir);
    vi.stubEnv('CARGO_HOME', emptyDir);
    bump({ alpha: '1.1.0' });

    try {
      await createGroupStrategy(baseConfig({ groups: { rust: { packages: ['alpha'], sync: 'fixed' } } }))(
        workspace(root, [crate(root, 'alpha'), crate(root, 'beta')]),
      );
    } finally {
      vi.unstubAllEnvs();
      fs.rmSync(emptyDir, { recursive: true, force: true });
    }

    expect(readLock()).toBe(renderLock({ alpha: '1.1.0', beta: '1.0.0' }));
    expect(lockWarnings()).toEqual([]);
  });

  it('should leave the lock untouched under dry-run', async () => {
    bump({ alpha: '1.1.0' });

    await createGroupStrategy(
      baseConfig({ dryRun: true, groups: { rust: { packages: ['alpha', 'beta'], sync: 'fixed' } } }),
    )(workspace(root, [crate(root, 'alpha'), crate(root, 'beta')]));

    expect(readLock()).toBe(renderLock({ alpha: '1.0.0', beta: '1.0.0' }));
  });

  it('should not create a lock when none is committed', async () => {
    fs.rmSync(lockPath);
    bump({ alpha: '1.1.0' });

    await createAsyncStrategy(baseConfig())(workspace(root, [crate(root, 'alpha'), crate(root, 'beta')]));

    expect(fs.existsSync(lockPath)).toBe(false);
    expect(fs.readFileSync(path.join(root, 'crates', 'alpha', 'Cargo.toml'), 'utf8')).toContain('version = "1.1.0"');
  });

  it('should warn and still bump Cargo.toml when the lock cannot be synced unambiguously', async () => {
    // A registry copy of beta at the target version: cargo would have to add a source to beta's
    // references, so the sync refuses to guess and leaves the lock for `cargo update` to fix.
    const ambiguous = `${renderLock({ alpha: '1.0.0', beta: '1.0.0' }).replace(' "beta",', ' "beta 1.0.0",')}\n[[package]]\nname = "beta"\nversion = "2.0.0"\nsource = "${REGISTRY}"\n`;
    fs.writeFileSync(lockPath, ambiguous);
    bump({ beta: '2.0.0' });

    await createAsyncStrategy(baseConfig())(workspace(root, [crate(root, 'alpha'), crate(root, 'beta')]));

    expect(readLock()).toBe(ambiguous);
    expect(fs.readFileSync(path.join(root, 'crates', 'beta', 'Cargo.toml'), 'utf8')).toContain('version = "2.0.0"');
    expect(lockWarnings()).toEqual([expect.stringContaining('Failed to sync Cargo.lock')]);
  });
});
